// Geometrías 3D de las criaturas. Son ORIGINALES de Fiora (sin modelos de terceros): cada animal es
// un volumen definido por un campo de distancia con signo, unión suave de elipsoides y conos
// redondeados colocados a mano. De ese volumen se sacan las partículas: la mayoría sobre la
// superficie y unas pocas en el interior, así la silueta se reconoce desde cualquier ángulo.
//
// Ejes: +x hacia donde mira el animal, +y arriba, z a los lados.
//   ['e', centro, radios, [giroX, giroY, giroZ] en grados]   elipsoide
//   ['c', a, b, radioA, radioB]                               cono redondeado entre dos puntos
//   En mayúscula ('E', 'C') la pieza se repite reflejada en z (patas, alas, orejas…).
//   chain(puntos [x, y, z, radio]…) encadena conos (colas, trompas, cuerpos curvos).

const chain = (pts, kind = 'c') => pts.slice(1).map((b, i) => [kind, pts[i].slice(0, 3), b.slice(0, 3), pts[i][3], b[3]]);

