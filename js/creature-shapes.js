// ------------------------------------------------------- campo de distancia
const rad = d => (d * Math.PI) / 180;
function matrix([ax = 0, ay = 0, az = 0] = []) {
  const [sx, cx, sy, cy, sz, cz] = [Math.sin(rad(ax)), Math.cos(rad(ax)), Math.sin(rad(ay)), Math.cos(rad(ay)), Math.sin(rad(az)), Math.cos(rad(az))];
  // R = Rz · Ry · Rx (filas)
  return [cz * cy, cz * sy * sx - sz * cx, cz * sy * cx + sz * sx, sz * cy, sz * sy * sx + cz * cx, sz * sy * cx - cz * sx, -sy, cy * sx, cy * cx];
}
function compile(parts) {
  return parts.map(p => {
    const mirror = p[0] === 'E' || p[0] === 'C';
    if (p[0].toLowerCase() === 'e') return { t: 0, mirror, c: p[1], r: p[2], m: p[3] ? matrix(p[3]) : null };
    const a = p[1], b = p[2], ba = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    return { t: 1, mirror, a, ba, l2: ba[0] * ba[0] + ba[1] * ba[1] + ba[2] * ba[2], r1: p[3], r2: p[4] };
  });
}
function partDist(q, x, y, z) {
  if (q.mirror) z = Math.abs(z);
  if (q.t === 0) {
    let dx = x - q.c[0], dy = y - q.c[1], dz = z - q.c[2];
    if (q.m) { const m = q.m, ux = m[0] * dx + m[3] * dy + m[6] * dz, uy = m[1] * dx + m[4] * dy + m[7] * dz, uz = m[2] * dx + m[5] * dy + m[8] * dz; dx = ux; dy = uy; dz = uz; }
    const r = q.r, k0 = Math.hypot(dx / r[0], dy / r[1], dz / r[2]), k1 = Math.hypot(dx / (r[0] * r[0]), dy / (r[1] * r[1]), dz / (r[2] * r[2]));
    return k1 > 1e-9 ? (k0 * (k0 - 1)) / k1 : -Math.min(r[0], r[1], r[2]);
  }
  const px = x - q.a[0], py = y - q.a[1], pz = z - q.a[2];
  const h = q.l2 > 1e-9 ? Math.max(0, Math.min(1, (px * q.ba[0] + py * q.ba[1] + pz * q.ba[2]) / q.l2)) : 0;
  return Math.hypot(px - q.ba[0] * h, py - q.ba[1] * h, pz - q.ba[2] * h) - (q.r1 + (q.r2 - q.r1) * h);
}
const K = 0.045;   // suavidad de las uniones
function sdf(parts, x, y, z) {
  let d = 1e9;
  for (const q of parts) {
    const e = partDist(q, x, y, z), h = Math.max(K - Math.abs(d - e), 0) / K;
    d = Math.min(d, e) - h * h * K * 0.25;
  }
  return d;
}
const compiled = new Map();
const partsOf = id => { if (!compiled.has(id)) compiled.set(id, compile(SHAPES[id].parts)); return compiled.get(id); };
/** Distancia con signo al animal (negativa dentro). Sirve para comprobar que cada geometría es distinta. */
export const distance = (id, x, y, z) => sdf(partsOf(id), x, y, z);

function rng(seed) { let a = seed >>> 0; return () => { a = (a + 0x6D2B79F5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const hash = s => { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return h >>> 0; };

const cache = new Map();
/**
 * n partículas del animal, centradas y con radio máximo 1: Float32Array [x, y, z, …].
 * El 82 % va a la superficie (se proyecta con el gradiente) y el resto al interior.
 */
export function sample(id, n) {
  const key = `${id}:${n}`;
  if (cache.has(key)) return cache.get(key);
  const parts = partsOf(id), rand = rng(hash(id) + n), out = new Float32Array(n * 3);
  // caja: por rejilla gruesa
  let lo = [9, 9, 9], hi = [-9, -9, -9];
  for (let x = -1.6; x <= 1.6; x += 0.1) for (let y = -1.2; y <= 1.2; y += 0.1) for (let z = -1.6; z <= 1.6; z += 0.1) {
    if (sdf(parts, x, y, z) < 0.06) { lo = [Math.min(lo[0], x), Math.min(lo[1], y), Math.min(lo[2], z)]; hi = [Math.max(hi[0], x), Math.max(hi[1], y), Math.max(hi[2], z)]; }
  }
  for (let i = 0; i < 3; i++) { lo[i] -= 0.1; hi[i] += 0.1; }
  const surface = Math.round(n * 0.82), e = 0.004;
  let i = 0, guard = 0;
  while (i < n && guard++ < n * 400) {
    let x = lo[0] + rand() * (hi[0] - lo[0]), y = lo[1] + rand() * (hi[1] - lo[1]), z = lo[2] + rand() * (hi[2] - lo[2]);
    let d = sdf(parts, x, y, z);
    if (i < surface) {
      if (Math.abs(d) > 0.09) continue;
      for (let it = 0; it < 2; it++) {
        const gx = sdf(parts, x + e, y, z) - sdf(parts, x - e, y, z), gy = sdf(parts, x, y + e, z) - sdf(parts, x, y - e, z), gz = sdf(parts, x, y, z + e) - sdf(parts, x, y, z - e);
        const gl = Math.hypot(gx, gy, gz) || 1;
        x -= (d * gx) / gl; y -= (d * gy) / gl; z -= (d * gz) / gl;
        d = sdf(parts, x, y, z);
      }
      if (Math.abs(d) > 0.012) continue;
    } else if (d > -0.015) continue;
    out[i * 3] = x; out[i * 3 + 1] = y; out[i * 3 + 2] = z; i++;
  }
  // centrar y normalizar
  const c = [(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, (lo[2] + hi[2]) / 2];
  let r = 0;
  for (let k = 0; k < i; k++) r = Math.max(r, Math.hypot(out[k * 3] - c[0], out[k * 3 + 1] - c[1], out[k * 3 + 2] - c[2]));
  const s = 1 / (r || 1);
  for (let k = 0; k < n; k++) for (let a = 0; a < 3; a++) out[k * 3 + a] = (out[k * 3 + a] - c[a]) * s;
  if (cache.size >= 4) cache.delete(cache.keys().next().value);   // como mucho, cuatro nubes en memoria
  cache.set(key, out);
  return out;
}

/** Nube sin silueta para «Tu criatura está tomando forma». */
export function nebula(n, seed = 7) {
  const rand = rng(seed), out = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) {
    const u = rand() * 2 - 1, th = rand() * Math.PI * 2, r = 0.25 + Math.pow(rand(), 0.6) * 0.7, s = Math.sqrt(1 - u * u);
    const arm = Math.sin(th * 2 + r * 5) * 0.12;
    out[i * 3] = (r + arm) * s * Math.cos(th); out[i * 3 + 1] = (r * 0.62) * u; out[i * 3 + 2] = (r + arm) * s * Math.sin(th);
  }
  return out;
}
